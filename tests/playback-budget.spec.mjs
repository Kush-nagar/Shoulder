import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";

/**
 * `docs/11-testing-quality.md`, Task 11: "measure a full 90-minute 720p
 * output on normal broadband: first frame, random seek p75, bytes
 * transferred, browser memory, and failure/retry behavior." The two named
 * budgets in `docs/02-architecture.md`'s performance table — first frame
 * < 2.5s, random seek < 1.5s p75 — are asserted; bytes transferred, memory,
 * and failure/retry have no numeric budget in either document, so this only
 * measures and records them rather than inventing a threshold.
 *
 * The fixture is a real 90-minute, 1280x720, fast-start H.264/AAC MP4
 * generated by the pinned ffmpeg (`scripts/seed_player_fixture.py`) and
 * published to the real local MinIO object storage — never committed
 * footage, and not a shortened stand-in. Chromium only: CDP network
 * emulation and `performance.memory` are Chromium APIs, and this is a
 * performance measurement rather than a cross-engine correctness suite —
 * `tests/player.spec.mjs` already covers cross-engine playback behavior.
 *
 * "Normal broadband" is not pinned to an exact figure anywhere in the docs.
 * This uses 10 Mbps down / 3 Mbps up / 40 ms RTT, a commonly used broadband
 * reference profile (comparable to WebPageTest's "Cable"/"Broadband"
 * presets); the exact numbers are recorded here and in the verification
 * record rather than left implicit.
 */

const api = "http://127.0.0.1:8000";
const mail = "http://127.0.0.1:54324";
const python =
  process.platform === "win32"
    ? ".venv/Scripts/python.exe"
    : ".venv/bin/python";

const DURATION_SECONDS = 90 * 60;
const DOWNLOAD_BYTES_PER_SECOND = (10 * 1000 * 1000) / 8;
const UPLOAD_BYTES_PER_SECOND = (3 * 1000 * 1000) / 8;
const LATENCY_MS = 40;
const SEEK_SAMPLES = 20;
const FIRST_FRAME_BUDGET_MS = 2500;
const SEEK_P75_BUDGET_MS = 1500;

let createdEmail;

function resetLocalWorkspace() {
  execFileSync(
    "docker",
    [
      "exec",
      "-i",
      "supabase_db_shoulder-local",
      "psql",
      "-U",
      "postgres",
      "-d",
      "postgres",
      "-q",
      "-v",
      "ON_ERROR_STOP=1",
      "-c",
      "TRUNCATE app.processing_job, app.video_upload_part, app.video, app.game, app.development_goal, app.player, app.team_membership, app.team",
    ],
    { stdio: ["ignore", "ignore", "pipe"] },
  );
}

function emptyLocalBucket() {
  execFileSync(
    "docker",
    [
      "compose",
      "--env-file",
      ".env.local",
      "-f",
      "infra/compose.yaml",
      "run",
      "--rm",
      "mc",
      "-ec",
      'mc alias set local http://minio:9000 "$MINIO_ROOT_USER" "$MINIO_ROOT_PASSWORD" >/dev/null; mc rm --recursive --force --dangerous local/shoulder-local >/dev/null 2>&1 || true',
    ],
    { stdio: ["ignore", "ignore", "pipe"] },
  );
}

test.beforeEach(() => {
  resetLocalWorkspace();
});

test.afterEach(async ({ request }) => {
  resetLocalWorkspace();
  emptyLocalBucket();
  if (!createdEmail) return;
  const status = JSON.parse(
    execFileSync(".tools/supabase/supabase.exe", ["status", "-o", "json"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }),
  );
  if (status.API_URL !== "http://127.0.0.1:54321")
    throw new Error("Local cleanup only");
  const headers = {
    apikey: status.SERVICE_ROLE_KEY,
    Authorization: `Bearer ${status.SERVICE_ROLE_KEY}`,
  };
  const users = await fetch(
    `${status.API_URL}/auth/v1/admin/users?filter=${encodeURIComponent(createdEmail)}`,
    { headers },
  );
  for (const user of (await users.json()).users.filter(
    (user) => user.email === createdEmail,
  )) {
    await fetch(`${status.API_URL}/auth/v1/admin/users/${user.id}`, {
      method: "DELETE",
      headers,
    });
  }
  const messages = await (await request.get(`${mail}/api/v1/messages`)).json();
  const ids = messages.messages
    .filter((message) => message.To.some((to) => to.Address === createdEmail))
    .map((message) => message.ID);
  if (ids.length)
    await request.delete(`${mail}/api/v1/messages`, { data: { IDs: ids } });
  createdEmail = undefined;
});

async function signIn(page, context, request) {
  const email = `project03-budget-${randomUUID()}@example.test`;
  createdEmail = email;
  await page.goto("/auth/sign-in");
  await page.getByLabel("Email address").fill(email);
  await page.getByRole("button", { name: "Email a sign-in link" }).click();
  await expect(page.getByRole("status")).toContainText("check your email");
  let messageId;
  await expect
    .poll(async () => {
      const listing = await (
        await request.get(`${mail}/api/v1/messages`)
      ).json();
      messageId = listing.messages.find((message) =>
        message.To.some((to) => to.Address === email),
      )?.ID;
      return Boolean(messageId);
    })
    .toBe(true);
  const message = await (
    await request.get(`${mail}/api/v1/message/${messageId}`)
  ).json();
  const link = message.HTML.match(
    /href="([^"]*\/auth\/v1\/verify[^"]*)"/,
  )[1].replaceAll("&amp;", "&");
  const verification = await request.get(link, { maxRedirects: 0 });
  await context.request.get(verification.headers().location, {
    maxRedirects: 0,
  });
}

async function bootstrapTeam(context, request) {
  const identity = await context.request.get("/api/auth/identity");
  const { user_id } = await identity.json();
  const created = await request.post(`${api}/v1/teams`, {
    headers: { "X-Operator-Token": process.env.OPERATOR_BOOTSTRAP_TOKEN ?? "" },
    data: {
      name: `Project 03 budget ${randomUUID().slice(0, 8)}`,
      age_group: "U14",
      coach_user_id: user_id,
      season_label: "Season 2026",
      season_end_at: new Date(Date.now() + 86_400_000).toISOString(),
    },
  });
  const { team_id } = await created.json();
  return { teamId: team_id, coachId: user_id };
}

function psql(sql) {
  return execFileSync(
    "docker",
    [
      "exec",
      "-i",
      "supabase_db_shoulder-local",
      "psql",
      "-U",
      "postgres",
      "-d",
      "postgres",
      "-v",
      "ON_ERROR_STOP=1",
      "-Atc",
      sql,
    ],
    { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  ).trim();
}

function quoted(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insertGame(teamId, coachId) {
  return psql(
    `INSERT INTO app.game (team_id, played_at, created_by) VALUES (${quoted(
      teamId,
    )}, now(), ${quoted(coachId)}) RETURNING id`,
  );
}

function insertReadyVideo(videoId, gameId, coachId, fixture) {
  psql(`
    INSERT INTO app.video (
      id, game_id, original_key, original_filename, content_type, size_bytes,
      uploaded_by, status, playback_key, duration_ms, width, height, fps, ready_at
    ) VALUES (
      ${quoted(videoId)}, ${quoted(gameId)}, ${quoted(`originals/${videoId}/source.mp4`)},
      'match.mp4', 'video/mp4', ${fixture.size_bytes}, ${quoted(coachId)}, 'ready',
      ${quoted(`playback/${videoId}/coach-720p.mp4`)}, ${fixture.duration_ms},
      ${fixture.width}, ${fixture.height}, ${fixture.fps}, now()
    )
  `);
}

/** A real 90-minute fixture. No sprites: this measures the playback route only. */
function seedFullLengthFixture(videoId) {
  return JSON.parse(
    execFileSync(
      python,
      [
        "-m",
        "scripts.seed_player_fixture",
        "--video-id",
        videoId,
        "--seconds",
        String(DURATION_SECONDS),
        "--skip-thumbnails",
      ],
      // A 90-minute encode is a multi-minute step; give it real room.
      {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "pipe"],
        timeout: 20 * 60 * 1000,
      },
    ),
  );
}

function percentile(samples, fraction) {
  const sorted = [...samples].sort((a, b) => a - b);
  const index = Math.min(
    sorted.length - 1,
    Math.ceil(fraction * sorted.length) - 1,
  );
  return sorted[index];
}

test("a full 90-minute coach playback meets the first-frame and seek budgets", async ({
  page,
  context,
  request,
}) => {
  test.setTimeout(20 * 60 * 1000);

  await signIn(page, context, request);
  const { teamId, coachId } = await bootstrapTeam(context, request);
  const gameId = insertGame(teamId, coachId);
  const videoId = randomUUID();
  const fixture = seedFullLengthFixture(videoId);
  insertReadyVideo(videoId, gameId, coachId, fixture);

  const client = await context.newCDPSession(page);
  await client.send("Network.enable");
  await client.send("Network.emulateNetworkConditions", {
    offline: false,
    downloadThroughput: DOWNLOAD_BYTES_PER_SECOND,
    uploadThroughput: UPLOAD_BYTES_PER_SECOND,
    latency: LATENCY_MS,
  });

  let videoBytes = 0;
  page.on("response", (response) => {
    if (!response.url().includes("127.0.0.1:9000")) return;
    const length = response.headers()["content-length"];
    if (length) videoBytes += Number(length);
  });

  const firstFrameStart = Date.now();
  await page.goto(`/coach/games/${gameId}`);
  await page.waitForFunction(
    () => (document.querySelector("video")?.readyState ?? 0) >= 2,
    { timeout: FIRST_FRAME_BUDGET_MS * 4 },
  );
  const firstFrameMs = Date.now() - firstFrameStart;
  const bytesForFirstFrame = videoBytes;

  const durationSeconds = fixture.duration_ms / 1000;
  const seekTimesMs = [];
  for (let sample = 0; sample < SEEK_SAMPLES; sample += 1) {
    const target = Math.random() * (durationSeconds - 1);
    // Each seek must finish before the next one is timed, so this stays serial.
    const elapsed = await page.evaluate((seconds) => {
      return new Promise((resolve) => {
        const video = document.querySelector("video");
        const start = performance.now();
        video.addEventListener(
          "seeked",
          () => resolve(performance.now() - start),
          { once: true },
        );
        video.currentTime = seconds;
      });
    }, target);
    seekTimesMs.push(elapsed);
  }
  const seekP75Ms = percentile(seekTimesMs, 0.75);

  const usedJSHeapBytes = await page.evaluate(
    () => performance.memory?.usedJSHeapSize ?? null,
  );

  // Failure/retry: a transient network interruption during playback, then
  // recovery. Nothing in `player.tsx` retries a stalled *decode* itself — only
  // the signed-URL refresh is custom logic — so this records the browser's own
  // native Range-request retry behavior on the progressive MP4, not a Shoulder
  // feature.
  await page.route("http://127.0.0.1:9000/**", (route) =>
    route.abort("connectionfailed"),
  );
  const seekDuringOutage = durationSeconds / 2;
  await page.evaluate((seconds) => {
    document.querySelector("video").currentTime = seconds;
  }, seekDuringOutage);
  await page.waitForTimeout(2000);
  await page.unroute("http://127.0.0.1:9000/**");
  const recoveredWithinFiveSeconds = await page
    .waitForFunction(
      () => {
        const video = document.querySelector("video");
        return video.readyState >= 2 && !video.error;
      },
      { timeout: 5000 },
    )
    .then(() => true)
    .catch(() => false);

  const summary = {
    fixture: {
      duration_ms: fixture.duration_ms,
      width: fixture.width,
      height: fixture.height,
      fps: fixture.fps,
      size_bytes: fixture.size_bytes,
    },
    network_profile: {
      download_mbps: (DOWNLOAD_BYTES_PER_SECOND * 8) / 1_000_000,
      upload_mbps: (UPLOAD_BYTES_PER_SECOND * 8) / 1_000_000,
      latency_ms: LATENCY_MS,
    },
    first_frame_ms: firstFrameMs,
    bytes_transferred_for_first_frame: bytesForFirstFrame,
    seek_samples_ms: seekTimesMs,
    seek_p75_ms: seekP75Ms,
    used_js_heap_bytes: usedJSHeapBytes,
    recovered_from_transient_network_failure: recoveredWithinFiveSeconds,
  };
  console.log(`PLAYBACK_BUDGET_RESULT ${JSON.stringify(summary)}`);

  expect(firstFrameMs, "first frame on normal broadband").toBeLessThan(
    FIRST_FRAME_BUDGET_MS,
  );
  expect(seekP75Ms, "random seek p75").toBeLessThan(SEEK_P75_BUDGET_MS);
});
