test.beforeEach(() => {
  resetLocalWorkspace();
});

test.afterEach(async ({ request }) => {
  resetLocalWorkspace();
  emptyLocalBucket();
  if (!createdEmail) return;
  const status = JSON.parse(
    execFileSync(".tools/supabase/supabase.exe", ["status", "-o", "json"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }),
  );
  if (status.API_URL !== "http://127.0.0.1:54321")
    throw new Error("Local cleanup only");
  const headers = {
    apikey: status.SERVICE_ROLE_KEY,
    Authorization: `Bearer ${status.SERVICE_ROLE_KEY}`,
  };
  const users = await fetch(
    `${status.API_URL}/auth/v1/admin/users?filter=${encodeURIComponent(createdEmail)}`,
    { headers },
  );
  if (!users.ok) throw new Error("Local fixture lookup failed");
  for (const user of (await users.json()).users.filter(
    (user) => user.email === createdEmail,
  )) {
    if (
      !(
        await fetch(`${status.API_URL}/auth/v1/admin/users/${user.id}`, {
          method: "DELETE",
          headers,
        })
      ).ok
    ) {
      throw new Error("Local fixture deletion failed");
    }
  }
  const messages = await (await request.get(`${mail}/api/v1/messages`)).json();
  const ids = messages.messages
    .filter((message) => message.To.some((to) => to.Address === createdEmail))
    .map((message) => message.ID);
  if (ids.length)
    await request.delete(`${mail}/api/v1/messages`, { data: { IDs: ids } });
  createdEmail = undefined;
});

async function signIn(page, context, request) {
  const email = `project03-${randomUUID()}@example.test`;
  createdEmail = email;
  await page.goto("/auth/sign-in");
  await page.getByLabel("Email address").fill(email);
  await page.getByRole("button", { name: "Email a sign-in link" }).click();
  await expect(page.getByRole("status")).toContainText("check your email");
  let messageId;
  await expect
    .poll(async () => {
      const listing = await (
        await request.get(`${mail}/api/v1/messages`)
      ).json();
      messageId = listing.messages.find((message) =>
        message.To.some((to) => to.Address === email),
      )?.ID;
      return Boolean(messageId);
    })
    .toBe(true);
  const message = await (
    await request.get(`${mail}/api/v1/message/${messageId}`)
  ).json();
  const link = message.HTML.match(
    /href="([^"]*\/auth\/v1\/verify[^"]*)"/,
  )[1].replaceAll("&amp;", "&");
  const verification = await request.get(link, { maxRedirects: 0 });
  const exchanged = await context.request.get(verification.headers().location, {
    maxRedirects: 0,
  });
  expect(exchanged.headers().location).toBe(`${origin}/auth/session`);
  return email;
}

/** Creates the team via the real API and returns the coach's identity too. */
async function bootstrapTeam(context, request) {
  const identity = await context.request.get("/api/auth/identity");
  expect(identity.status()).toBe(200);
  const { user_id } = await identity.json();
  const created = await request.post(`${api}/v1/teams`, {
    headers: {
      "X-Operator-Token": process.env.OPERATOR_BOOTSTRAP_TOKEN ?? "",
    },
    data: {
      name: `Project 03 ${randomUUID().slice(0, 8)}`,
      age_group: "U14",
      coach_user_id: user_id,
      season_label: "Season 2026",
      season_end_at: new Date(Date.now() + 86_400_000).toISOString(),
    },
  });
  expect(created.status()).toBe(201);
  const { team_id } = await created.json();
  return { teamId: team_id, coachId: user_id };
}

function psql(sql) {
  return execFileSync(
    "docker",
    [
      "exec",
      "-i",
      "supabase_db_shoulder-local",
      "psql",
      "-U",
      "postgres",
      "-d",
      "postgres",
      "-q",
      "-v",
      "ON_ERROR_STOP=1",
      "-Atc",
      sql,
    ],
    { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  ).trim();
}

function quoted(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insertGame(teamId, coachId) {
  return psql(
    `INSERT INTO app.game (team_id, played_at, created_by) VALUES (${quoted(
      teamId,
    )}, now(), ${quoted(coachId)}) RETURNING id`,
  );
}

function insertReadyVideo(videoId, gameId, coachId, fixture) {
  psql(`
    INSERT INTO app.video (
      id, game_id, original_key, original_filename, content_type, size_bytes,
      uploaded_by, status, playback_key, duration_ms, width, height, fps, ready_at,
      derivatives_expires_at
    ) VALUES (
      ${quoted(videoId)}, ${quoted(gameId)}, ${quoted(`originals/${videoId}/source.mp4`)},
      'match.mp4', 'video/mp4', 1, ${quoted(coachId)}, 'ready',
      ${quoted(`playback/${videoId}/coach-720p.mp4`)}, ${fixture.duration_ms},
      ${fixture.width}, ${fixture.height}, ${fixture.fps}, now(),
      now() + interval '30 days'
    )
  `);
}

/** Generates and publishes one real playback object plus its sprite timeline. */
function seedFixture(videoId, seconds = 15) {
  return JSON.parse(
    execFileSync(
      python,
      [
        "-m",
        "scripts.seed_player_fixture",
        "--video-id",
        videoId,
        "--seconds",
        String(seconds),
      ],
      { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
    ),
  );
}

/** Signs in, creates a team, a game, and one ready video a browser can play. */
async function readyGame(page, context, request, seconds = 15) {
  await signIn(page, context, request);
  const { teamId, coachId } = await bootstrapTeam(context, request);
  const gameId = insertGame(teamId, coachId);
  const videoId = randomUUID();
  const fixture = seedFixture(videoId, seconds);
  insertReadyVideo(videoId, gameId, coachId, fixture);
  return { gameId, videoId, fixture };
}

async function openPlayer(page, gameId) {
  await page.goto(`/coach/games/${gameId}`);
  const video = page.locator("video");
  await expect(video).toBeVisible();
  await page.waitForFunction(
    () => (document.querySelector("video")?.duration ?? 0) > 0,
  );
  return video;
}

function currentTime(video) {
  return video.evaluate((element) => element.currentTime);
}

test("keyboard transport plays, pauses, and steps the playhead", async ({
  page,
  context,
  request,
}) => {
  const { gameId } = await readyGame(page, context, request);
  const video = await openPlayer(page, gameId);

  await page.keyboard.press(" ");
  await expect
    .poll(() => video.evaluate((element) => element.paused))
    .toBe(false);
  await page.keyboard.press(" ");
  await expect
    .poll(() => video.evaluate((element) => element.paused))
    .toBe(true);

  await page.keyboard.press("l");
  await expect.poll(() => currentTime(video)).toBeCloseTo(10, 0);

  await page.keyboard.press("Shift+ArrowLeft");
  await expect.poll(() => currentTime(video)).toBeCloseTo(0, 0);

  await page.keyboard.press("ArrowRight");
  await expect.poll(() => currentTime(video)).toBeCloseTo(1, 0);

  await page.keyboard.press("j");
  await expect.poll(() => currentTime(video)).toBeCloseTo(0, 0);
});

test("the scrubber seeks and previews the sprite timeline on hover", async ({
  page,
  context,
  request,
}) => {
  const { gameId, videoId, fixture } = await readyGame(page, context, request);
  await openPlayer(page, gameId);

  const scrubber = page.getByLabel("Seek through the match");
  await expect(scrubber).toHaveAttribute(
    "max",
    String(Math.round(fixture.duration_ms)),
  );

  const box = await scrubber.boundingBox();
  // `.hover()` rather than a raw `page.mouse.move`: it waits for the element
  // to be actionable and positions relative to it, so the event reliably
  // reaches the input itself rather than whatever else is at that viewport
  // coordinate.
  await scrubber.hover({ position: { x: box.width * 0.6, y: box.height / 2 } });
  // Scoped to the player section: the coach shell's own nav tooltips share
  // both `aria-hidden="true"` and the `border-line` class.
  const preview = page
    .locator("section:has(#scrubber)")
    .locator('[aria-hidden="true"].border-line');
  await expect(preview).toBeVisible();
  const style = await preview.getAttribute("style");
  expect(style).toContain(`thumbs/${videoId}/sprite-`);

  await scrubber.fill(String(Math.round(fixture.duration_ms * 0.4)));
  const video = page.locator("video");
  await expect
    .poll(() => currentTime(video))
    .toBeCloseTo((fixture.duration_ms * 0.4) / 1000, 0);
});

test("the signed URL refreshes before it expires and keeps the playhead", async ({
  page,
  context,
  request,
}) => {
  const { gameId } = await readyGame(page, context, request);
  await page.clock.install();
  const video = await openPlayer(page, gameId);

  await video.evaluate((element) => {
    element.currentTime = 4;
  });
  await page.keyboard.press(" ");
  await expect
    .poll(() => video.evaluate((element) => element.paused))
    .toBe(false);

  let refreshed = false;
  page.on("request", (sent) => {
    if (sent.url().includes("/playback-url") && sent.method() === "POST")
      refreshed = true;
  });

  // The player schedules its refresh at `expires_in - 120s`, floored at 60s;
  // the coach ceiling is 900s, so the real timer would be 780s from now.
  await page.clock.fastForward("13:05");

  await expect.poll(() => refreshed).toBe(true);
  // Not a same-URL check: two signatures minted within the same wall-clock
  // second are byte-identical (`X-Amz-Date` is second-granular), so a
  // coincidental match would be a false failure rather than evidence the
  // refresh didn't happen. The restored playhead/play-state below only exist
  // because `load()`'s `setPlayback` updater actually ran.
  await expect.poll(() => currentTime(video)).toBeCloseTo(4, 0);
  await expect
    .poll(() => video.evaluate((element) => element.paused))
    .toBe(false);
});

test("a failed refresh tells the coach to reload rather than silently stopping", async ({
  page,
  context,
  request,
}) => {
  const { gameId } = await readyGame(page, context, request);
  await page.clock.install();
  const video = await openPlayer(page, gameId);
  await video.evaluate((element) => {
    element.currentTime = 2;
  });

  // The route is only installed after the initial load already succeeded,
  // so the one call it ever intercepts is the scheduled refresh itself.
  await page.route("**/api/videos/*/playback-url", (route) =>
    route.fulfill({ status: 500, body: "" }),
  );

  await page.clock.fastForward("13:05");

  // Scoped to the player section: Next's own route announcer also carries
  // role="alert", unscoped would be a strict-mode violation once this one
  // renders too.
  await expect(
    page
      .locator('section[aria-labelledby="player-heading"]')
      .getByRole("alert"),
  ).toContainText("Playback expired. Reload the page to continue.");
});
