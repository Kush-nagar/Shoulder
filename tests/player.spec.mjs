/**
 * Task 13 acceptance against a real browser: keyboard transport, the signed
 * playback URL refreshing before it expires while the playhead survives the
 * swap, the fallback when a refresh fails, and the scrubber's thumbnail
 * timeline. `docs/05-ui.md`'s keyboard map and the coach playback object's
 * fifteen-minute signature (`docs/10-security-privacy.md`) are both exercised
 * for real: nothing here is a unit-test stand-in for what only a browser can
 * prove.
 *
 * The video itself is generated by the pinned ffmpeg at run time
 * (`scripts/seed_player_fixture.py`, the same shape `tests/test_media.py`
 * uses) and published through the real storage functions in
 * `services/api/storage.py`. Never committed footage.
 */

const origin = "http://127.0.0.1:3000";
const api = "http://127.0.0.1:8000";
const mail = "http://127.0.0.1:54324";
const python =
  process.platform === "win32"
    ? ".venv/Scripts/python.exe"
    : ".venv/bin/python";

let createdEmail;

